/* Pasa a DIM_HOMOLOGADOS los candidatos con DECISION = 'SI' (aún no aplicados).
   Uso:  UPDATE dbo.HOMOLOGACION_REVISION SET DECISION = 'SI', FECHA_DECISION = GETDATE(),
                USUARIO_DECISION = SUSER_SNAME() WHERE ID_REVISION IN (...);
         EXEC dbo.usp_HOMOLOGACION_APROBAR_REVISION;            -- vista previa
         EXEC dbo.usp_HOMOLOGACION_APROBAR_REVISION @Aplicar = 1; */
IF OBJECT_ID('dbo.usp_HOMOLOGACION_APROBAR_REVISION', 'P') IS NOT NULL DROP PROCEDURE dbo.usp_HOMOLOGACION_APROBAR_REVISION;
GO
CREATE PROCEDURE dbo.usp_HOMOLOGACION_APROBAR_REVISION
    @Aplicar BIT = 0
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SELECT r.ID_REVISION, r.FUENTE, c.ID_SKU_EXTERNO_CANONICO AS ID_SKU_EXTERNO, c.DESC_PRODUCTO_EXTERNO,
           r.ID_SKU_UNICO_UNILENE, r.ID_SKU_UNILENE, i.Agrupador, i.SubFamilia
    INTO #aprobar
    FROM dbo.HOMOLOGACION_REVISION r
    JOIN dbo.DIM_PRODUCTO_EXTERNO p ON p.FUENTE = r.FUENTE AND p.ID_SKU_EXTERNO = r.ID_SKU_EXTERNO
    JOIN dbo.DIM_PRODUCTO_EXTERNO c ON c.FUENTE = p.FUENTE AND c.ID_SKU_EXTERNO = p.ID_SKU_EXTERNO_CANONICO
    LEFT JOIN dbo.STG_ITEMS i ON i.Coditem = r.ID_SKU_UNILENE
    WHERE r.DECISION = 'SI' AND r.FECHA_APLICACION IS NULL;

    IF @Aplicar = 0
    BEGIN
        SELECT * FROM #aprobar ORDER BY ID_SKU_EXTERNO, ID_SKU_UNILENE;
        RETURN;
    END

    BEGIN TRANSACTION;

    INSERT INTO dbo.DIM_HOMOLOGADOS (ID_SKU_EXTERNO, DESC_PRODUCTO_EXTERNO, FUENTE, ID_SKU_UNICO_UNILENE, ID_SKU_UNILENE,
                                     AGRUPADOR, SUBAGRUPADOR, DPRO_DESC_SUB_FAMILIA, VALIDACION, NIVEL, ORIGEN)
    SELECT a.ID_SKU_EXTERNO, a.DESC_PRODUCTO_EXTERNO, a.FUENTE, a.ID_SKU_UNICO_UNILENE, a.ID_SKU_UNILENE,
           a.Agrupador,
           CASE WHEN a.Agrupador = N'01. SUTURAS' THEN N'SUTURAS' ELSE a.SubFamilia END,
           a.SubFamilia, 'OK', 'REVISION', N'Aprobado en HOMOLOGACION_REVISION'
    FROM #aprobar a
    WHERE NOT EXISTS (SELECT 1 FROM dbo.DIM_HOMOLOGADOS h
                      WHERE h.FUENTE = a.FUENTE AND h.ID_SKU_EXTERNO = a.ID_SKU_EXTERNO AND h.ID_SKU_UNILENE = a.ID_SKU_UNILENE);

    UPDATE p SET TIENE_HOMOLOGACION = 1, FECHA_MODIFICACION = GETDATE()
    FROM dbo.DIM_PRODUCTO_EXTERNO p
    WHERE EXISTS (SELECT 1 FROM #aprobar a WHERE a.FUENTE = p.FUENTE AND a.ID_SKU_EXTERNO = p.ID_SKU_EXTERNO);

    UPDATE r SET FECHA_APLICACION = GETDATE()
    FROM dbo.HOMOLOGACION_REVISION r
    WHERE EXISTS (SELECT 1 FROM #aprobar a WHERE a.ID_REVISION = r.ID_REVISION);

    COMMIT TRANSACTION;

    SELECT COUNT(*) AS filas_aplicadas FROM #aprobar;
END
GO

/* Completa familias: para cada código externo OK, agrega los Coditem de STG_ITEMS con el mismo
   ID_SKU_UNICO (CodSut pos. 3-15 + 'B' si doble aguja) y marca SD/CQ que aún no estén.
   Requiere dbo.STG_ITEMS cargada.  @Aplicar = 0 -> solo muestra. */
IF OBJECT_ID('dbo.usp_HOMOLOGACION_COMPLETAR_FAMILIAS', 'P') IS NOT NULL DROP PROCEDURE dbo.usp_HOMOLOGACION_COMPLETAR_FAMILIAS;
GO
CREATE PROCEDURE dbo.usp_HOMOLOGACION_COMPLETAR_FAMILIAS
    @Fuente  VARCHAR(20) = 'MINSA',
    @Aplicar BIT = 0
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    ;WITH items AS (
        SELECT Coditem, Agrupador, SubFamilia,
               CASE WHEN Agrupador = N'01. SUTURAS' AND LEN(CodSut) = 21
                    THEN SUBSTRING(CodSut, 3, 13) + CASE WHEN SUBSTRING(CodSut, 18, 1) = 'B' THEN 'B' ELSE '' END
                    ELSE Coditem END AS UNICO,
               CASE WHEN Agrupador = N'01. SUTURAS' AND LEN(CodSut) = 21 THEN LEFT(CodSut, 2) ELSE '' END AS MARCA
        FROM dbo.STG_ITEMS
    ), base AS (
        SELECT DISTINCT FUENTE, ID_SKU_EXTERNO, DESC_PRODUCTO_EXTERNO, ID_SKU_UNICO_UNILENE
        FROM dbo.DIM_HOMOLOGADOS
        WHERE FUENTE = @Fuente AND VALIDACION = 'OK'
    )
    SELECT b.FUENTE, b.ID_SKU_EXTERNO, b.DESC_PRODUCTO_EXTERNO, b.ID_SKU_UNICO_UNILENE, i.Coditem AS ID_SKU_UNILENE,
           i.Agrupador, i.SubFamilia
    INTO #nuevos
    FROM base b
    JOIN items i ON i.UNICO = b.ID_SKU_UNICO_UNILENE AND (i.MARCA IN ('SD', 'CQ') OR i.MARCA = '')
    WHERE NOT EXISTS (SELECT 1 FROM dbo.DIM_HOMOLOGADOS h
                      WHERE h.FUENTE = b.FUENTE AND h.ID_SKU_EXTERNO = b.ID_SKU_EXTERNO AND h.ID_SKU_UNILENE = i.Coditem);

    IF @Aplicar = 0
    BEGIN
        SELECT * FROM #nuevos ORDER BY ID_SKU_EXTERNO, ID_SKU_UNILENE;
        RETURN;
    END

    INSERT INTO dbo.DIM_HOMOLOGADOS (ID_SKU_EXTERNO, DESC_PRODUCTO_EXTERNO, FUENTE, ID_SKU_UNICO_UNILENE, ID_SKU_UNILENE,
                                     AGRUPADOR, SUBAGRUPADOR, DPRO_DESC_SUB_FAMILIA, VALIDACION, NIVEL, ORIGEN)
    SELECT ID_SKU_EXTERNO, DESC_PRODUCTO_EXTERNO, FUENTE, ID_SKU_UNICO_UNILENE, ID_SKU_UNILENE,
           Agrupador, CASE WHEN Agrupador = N'01. SUTURAS' THEN N'SUTURAS' ELSE SubFamilia END, SubFamilia,
           'OK', 'EXACTO', N'Completar familia (usp)'
    FROM #nuevos;

    SELECT @@ROWCOUNT AS filas_agregadas;
END
GO
