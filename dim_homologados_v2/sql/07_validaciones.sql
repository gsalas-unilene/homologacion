/* 07 – Validaciones de calidad DIM_HOMOLOGADOS v2 (SQL Server 2012)
   Todas las consultas marcadas "debe ser 0" deben devolver 0 filas / 0. */
SET NOCOUNT ON;
GO

-- Resumen
SELECT FUENTE, VALIDACION, NIVEL, COUNT(*) AS filas, COUNT(DISTINCT ID_SKU_EXTERNO) AS codigos_externos
FROM dbo.DIM_HOMOLOGADOS GROUP BY FUENTE, VALIDACION, NIVEL ORDER BY FUENTE, VALIDACION, NIVEL;

SELECT FUENTE, VALIDACION_SIGA, COUNT(*) AS productos, SUM(CONVERT(INT, ES_DUPLICADO)) AS duplicados
FROM dbo.DIM_PRODUCTO_EXTERNO GROUP BY FUENTE, VALIDACION_SIGA;

-- 1) debe ser 0: códigos duplicados (no canónicos) con filas en DIM_HOMOLOGADOS
SELECT h.FUENTE, h.ID_SKU_EXTERNO, p.ID_SKU_EXTERNO_CANONICO, COUNT(*) AS filas
FROM dbo.DIM_HOMOLOGADOS h
JOIN dbo.DIM_PRODUCTO_EXTERNO p ON p.FUENTE = h.FUENTE AND p.ID_SKU_EXTERNO = h.ID_SKU_EXTERNO
WHERE p.ES_DUPLICADO = 1
GROUP BY h.FUENTE, h.ID_SKU_EXTERNO, p.ID_SKU_EXTERNO_CANONICO;

-- 2) debe ser 0: canónico inexistente
SELECT p.* FROM dbo.DIM_PRODUCTO_EXTERNO p
WHERE NOT EXISTS (SELECT 1 FROM dbo.DIM_PRODUCTO_EXTERNO c
                  WHERE c.FUENTE = p.FUENTE AND c.ID_SKU_EXTERNO = p.ID_SKU_EXTERNO_CANONICO);

-- 3) debe ser 0: SKU que no existe en el maestro (requiere STG_ITEMS cargada)
IF EXISTS (SELECT 1 FROM dbo.STG_ITEMS)
    SELECT h.FUENTE, h.ID_SKU_EXTERNO, h.ID_SKU_UNILENE, h.VALIDACION
    FROM dbo.DIM_HOMOLOGADOS h
    WHERE NOT EXISTS (SELECT 1 FROM dbo.STG_ITEMS i WHERE i.Coditem = h.ID_SKU_UNILENE)
      AND h.VALIDACION = 'OK';

-- 4) debe ser 0: ID_SKU_UNICO distinto al calculado desde el CodSut (requiere STG_ITEMS)
IF EXISTS (SELECT 1 FROM dbo.STG_ITEMS)
    SELECT h.ID_SKU_EXTERNO, h.ID_SKU_UNILENE, h.ID_SKU_UNICO_UNILENE, x.UNICO
    FROM dbo.DIM_HOMOLOGADOS h
    JOIN (SELECT Coditem,
                 CASE WHEN Agrupador = N'01. SUTURAS' AND LEN(CodSut) = 21
                      THEN SUBSTRING(CodSut, 3, 13) + CASE WHEN SUBSTRING(CodSut, 18, 1) = 'B' THEN 'B' ELSE '' END
                      ELSE Coditem END AS UNICO
          FROM dbo.STG_ITEMS) x ON x.Coditem = h.ID_SKU_UNILENE
    WHERE ISNULL(h.ID_SKU_UNICO_UNILENE, '') <> x.UNICO;

-- 5) debe ser 0: doble aguja inconsistente (MINSA dice doble aguja y el SKU no, o al revés) con VALIDACION = OK
SELECT h.ID_SKU_EXTERNO, h.DESC_PRODUCTO_EXTERNO, h.ID_SKU_UNILENE, h.ID_SKU_UNICO_UNILENE
FROM dbo.DIM_HOMOLOGADOS h
WHERE h.FUENTE = 'MINSA' AND h.AGRUPADOR = N'01. SUTURAS' AND h.VALIDACION = 'OK'
  AND (CASE WHEN h.DESC_PRODUCTO_EXTERNO LIKE N'%C/2A%' OR h.DESC_PRODUCTO_EXTERNO LIKE N'%C/2 A%'
              OR h.DESC_PRODUCTO_EXTERNO LIKE N'%DOBLE AGUJA%' OR h.DESC_PRODUCTO_EXTERNO LIKE N'% 2C/A%' THEN 1 ELSE 0 END)
      <> (CASE WHEN RIGHT(h.ID_SKU_UNICO_UNILENE, 1) = 'B' THEN 1 ELSE 0 END);

-- 6) debe ser 0: VALIDACION_SIGA = OK sin código
SELECT * FROM dbo.DIM_PRODUCTO_EXTERNO WHERE VALIDACION_SIGA = 'OK' AND CodigoSIGA IS NULL;

-- 7) informativo: un mismo CodigoSIGA en varios productos canónicos (posible duplicado no detectado)
SELECT CodigoSIGA, COUNT(*) AS productos, MIN(ID_SKU_EXTERNO) AS ejemplo1, MAX(ID_SKU_EXTERNO) AS ejemplo2
FROM dbo.DIM_PRODUCTO_EXTERNO
WHERE CodigoSIGA IS NOT NULL AND ES_DUPLICADO = 0 AND TIENE_HOMOLOGACION = 1
GROUP BY CodigoSIGA HAVING COUNT(*) > 1;

-- 8) informativo: pendientes de revisión por origen
SELECT ORIGEN, VENDIDO_MINSA, COUNT(*) AS filas, COUNT(DISTINCT ID_SKU_EXTERNO) AS codigos
FROM dbo.HOMOLOGACION_REVISION WHERE DECISION IS NULL GROUP BY ORIGEN, VENDIDO_MINSA ORDER BY ORIGEN, VENDIDO_MINSA;
GO
