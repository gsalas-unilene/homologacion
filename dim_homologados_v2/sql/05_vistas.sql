SET NOCOUNT ON;
GO

/* Vista compatible con el formato anterior (incluye CodigoSIGA y VALIDACION).
   Úsela en reportes / SSIS que leían dbo.DIM_HOMOLOGADOS. Excluye RECHAZADO. */
IF OBJECT_ID('dbo.VW_DIM_HOMOLOGADOS', 'V') IS NOT NULL DROP VIEW dbo.VW_DIM_HOMOLOGADOS;
GO
CREATE VIEW dbo.VW_DIM_HOMOLOGADOS
AS
SELECT h.ID_SKU_EXTERNO,
       h.DESC_PRODUCTO_EXTERNO,
       h.FUENTE,
       h.ID_SKU_UNICO_UNILENE,
       h.ID_SKU_UNILENE,
       h.AGRUPADOR,
       h.SUBAGRUPADOR,
       h.AGRUPADOR_NEWCOMERCIAL,
       h.SUB_AGRUPADOR_NEWCOMERCIAL,
       h.LINEA_NEWCOMERCIAL,
       h.DPRO_DESC_SUB_FAMILIA,
       p.CodigoSIGA,
       h.VALIDACION,
       h.NIVEL,
       h.MOTIVO_REVISION
FROM dbo.DIM_HOMOLOGADOS h
JOIN dbo.DIM_PRODUCTO_EXTERNO p
  ON p.FUENTE = h.FUENTE AND p.ID_SKU_EXTERNO = h.ID_SKU_EXTERNO
WHERE h.VALIDACION <> 'RECHAZADO';
GO

/* Resolución para tablas de hechos (ventas/compras MINSA): acepta CUALQUIER código externo,
   incluidos los duplicados, y devuelve los SKU del código canónico. */
IF OBJECT_ID('dbo.VW_HOMOLOGACION_RESUELTA', 'V') IS NOT NULL DROP VIEW dbo.VW_HOMOLOGACION_RESUELTA;
GO
CREATE VIEW dbo.VW_HOMOLOGACION_RESUELTA
AS
SELECT p.FUENTE,
       p.ID_SKU_EXTERNO,                       -- código tal como llega en la fuente
       p.ID_SKU_EXTERNO_CANONICO,
       p.ES_DUPLICADO,
       c.DESC_PRODUCTO_EXTERNO AS DESC_PRODUCTO_CANONICO,
       c.CodigoSIGA,
       c.VALIDACION_SIGA,
       h.ID_SKU_UNICO_UNILENE,
       h.ID_SKU_UNILENE,
       h.AGRUPADOR,
       h.SUBAGRUPADOR,
       h.VALIDACION,
       h.NIVEL
FROM dbo.DIM_PRODUCTO_EXTERNO p
JOIN dbo.DIM_PRODUCTO_EXTERNO c
  ON c.FUENTE = p.FUENTE AND c.ID_SKU_EXTERNO = p.ID_SKU_EXTERNO_CANONICO
JOIN dbo.DIM_HOMOLOGADOS h
  ON h.FUENTE = c.FUENTE AND h.ID_SKU_EXTERNO = c.ID_SKU_EXTERNO
WHERE h.VALIDACION <> 'RECHAZADO';
GO

/* Pendientes de decisión, ordenados para revisar primero lo que se vende */
IF OBJECT_ID('dbo.VW_HOMOLOGACION_PENDIENTE', 'V') IS NOT NULL DROP VIEW dbo.VW_HOMOLOGACION_PENDIENTE;
GO
CREATE VIEW dbo.VW_HOMOLOGACION_PENDIENTE
AS
SELECT r.ID_REVISION,
       r.FUENTE,
       r.ID_SKU_EXTERNO,
       p.DESC_PRODUCTO_EXTERNO,
       r.ID_SKU_UNILENE,
       r.ITEM_UNILENE,
       r.TIER_COL_F,
       r.COL,
       r.PRIORIDAD,
       r.DIFERENCIAS,
       r.VENDIDO_MINSA,
       r.ORIGEN,
       CASE WHEN r.VENDIDO_MINSA = 'SI' THEN 1 ELSE 2 END AS ORDEN_REVISION
FROM dbo.HOMOLOGACION_REVISION r
LEFT JOIN dbo.DIM_PRODUCTO_EXTERNO p
  ON p.FUENTE = r.FUENTE AND p.ID_SKU_EXTERNO = r.ID_SKU_EXTERNO
WHERE r.DECISION IS NULL;
GO
