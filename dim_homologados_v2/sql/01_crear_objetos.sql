GO

/* 6) Migrar filas de otras fuentes desde el respaldo (no MINSA) ---------------------------------- */
IF OBJECT_ID('dbo.DIM_HOMOLOGADOS_BK_20261006', 'U') IS NOT NULL
BEGIN
    BEGIN TRANSACTION;

    INSERT INTO dbo.DIM_PRODUCTO_EXTERNO (FUENTE, ID_SKU_EXTERNO, DESC_PRODUCTO_EXTERNO, ID_SKU_EXTERNO_CANONICO,
                                          ES_DUPLICADO, EN_CATALOGO_MINSA, VALIDACION_SIGA, TIENE_HOMOLOGACION)
    SELECT b.FUENTE, b.ID_SKU_EXTERNO, MAX(CONVERT(NVARCHAR(300), b.DESC_PRODUCTO_EXTERNO)), b.ID_SKU_EXTERNO,
           0, 0, 'SIN_DATO', 1
    FROM (SELECT LTRIM(RTRIM(CONVERT(VARCHAR(20), FUENTE))) AS FUENTE,
                 LTRIM(RTRIM(CONVERT(VARCHAR(50), ID_SKU_EXTERNO))) AS ID_SKU_EXTERNO, DESC_PRODUCTO_EXTERNO
          FROM dbo.DIM_HOMOLOGADOS_BK_20261006
          WHERE ISNULL(FUENTE, '') <> 'MINSA') b
    WHERE NOT EXISTS (SELECT 1 FROM dbo.DIM_PRODUCTO_EXTERNO p
                      WHERE p.FUENTE = b.FUENTE AND p.ID_SKU_EXTERNO = b.ID_SKU_EXTERNO)
    GROUP BY b.FUENTE, b.ID_SKU_EXTERNO;

    ;WITH src AS (
        SELECT LTRIM(RTRIM(CONVERT(VARCHAR(50), ID_SKU_EXTERNO))) AS ID_SKU_EXTERNO,
               CONVERT(NVARCHAR(300), DESC_PRODUCTO_EXTERNO) AS DESC_PRODUCTO_EXTERNO,
               LTRIM(RTRIM(CONVERT(VARCHAR(20), FUENTE))) AS FUENTE,
               CONVERT(VARCHAR(30), ID_SKU_UNICO_UNILENE) AS ID_SKU_UNICO_UNILENE,
               LTRIM(RTRIM(CONVERT(VARCHAR(20), ID_SKU_UNILENE))) AS ID_SKU_UNILENE,
               CONVERT(NVARCHAR(100), AGRUPADOR) AS AGRUPADOR, CONVERT(NVARCHAR(150), SUBAGRUPADOR) AS SUBAGRUPADOR,
               CONVERT(NVARCHAR(100), AGRUPADOR_NEWCOMERCIAL) AS AGRUPADOR_NEWCOMERCIAL,
               CONVERT(NVARCHAR(150), SUB_AGRUPADOR_NEWCOMERCIAL) AS SUB_AGRUPADOR_NEWCOMERCIAL,
               CONVERT(NVARCHAR(100), LINEA_NEWCOMERCIAL) AS LINEA_NEWCOMERCIAL,
               CONVERT(NVARCHAR(150), DPRO_DESC_SUB_FAMILIA) AS DPRO_DESC_SUB_FAMILIA,
               ROW_NUMBER() OVER (PARTITION BY FUENTE, ID_SKU_EXTERNO, ID_SKU_UNILENE ORDER BY (SELECT 0)) AS rn
        FROM dbo.DIM_HOMOLOGADOS_BK_20261006
        WHERE ISNULL(FUENTE, '') <> 'MINSA' AND ID_SKU_UNILENE IS NOT NULL
    )
    INSERT INTO dbo.DIM_HOMOLOGADOS (ID_SKU_EXTERNO, DESC_PRODUCTO_EXTERNO, FUENTE, ID_SKU_UNICO_UNILENE, ID_SKU_UNILENE,
                                     AGRUPADOR, SUBAGRUPADOR, AGRUPADOR_NEWCOMERCIAL, SUB_AGRUPADOR_NEWCOMERCIAL,
                                     LINEA_NEWCOMERCIAL, DPRO_DESC_SUB_FAMILIA, VALIDACION, NIVEL, ORIGEN)
    SELECT s.ID_SKU_EXTERNO, s.DESC_PRODUCTO_EXTERNO, s.FUENTE, s.ID_SKU_UNICO_UNILENE, s.ID_SKU_UNILENE,
           s.AGRUPADOR, s.SUBAGRUPADOR, s.AGRUPADOR_NEWCOMERCIAL, s.SUB_AGRUPADOR_NEWCOMERCIAL,
           s.LINEA_NEWCOMERCIAL, s.DPRO_DESC_SUB_FAMILIA, 'OK', 'EXACTO', N'Migración desde tabla anterior'
    FROM src s
    WHERE s.rn = 1
      AND NOT EXISTS (SELECT 1 FROM dbo.DIM_HOMOLOGADOS h
                      WHERE h.FUENTE = s.FUENTE AND h.ID_SKU_EXTERNO = s.ID_SKU_EXTERNO AND h.ID_SKU_UNILENE = s.ID_SKU_UNILENE);

    COMMIT TRANSACTION;

    SELECT FUENTE, COUNT(*) AS filas_migradas FROM dbo.DIM_HOMOLOGADOS GROUP BY FUENTE;
END
GO
