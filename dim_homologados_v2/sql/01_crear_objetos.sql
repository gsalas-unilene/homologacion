/* 01 – Crear objetos DIM_HOMOLOGADOS v2
   Compatible con SQL Server 2012. Ejecutar UNA vez, antes de 02/03/04.

   - Si existe la tabla anterior dbo.DIM_HOMOLOGADOS (sin columna ID_HOMOLOGACION) se renombra a
     dbo.DIM_HOMOLOGADOS_BK_20261006 (respaldo intacto).
   - Crea: DIM_PRODUCTO_EXTERNO, DIM_HOMOLOGADOS, HOMOLOGACION_REVISION, STG_ITEMS.
   - Migra las filas de otras fuentes (FUENTE <> 'MINSA') desde el respaldo, para no perderlas.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

/* 1) Respaldo de la tabla anterior --------------------------------------------------------------- */
IF OBJECT_ID('dbo.DIM_HOMOLOGADOS', 'U') IS NOT NULL
   AND COL_LENGTH('dbo.DIM_HOMOLOGADOS', 'ID_HOMOLOGACION') IS NULL
   AND OBJECT_ID('dbo.DIM_HOMOLOGADOS_BK_20261006', 'U') IS NULL
BEGIN
    EXEC sp_rename 'dbo.DIM_HOMOLOGADOS', 'DIM_HOMOLOGADOS_BK_20261006';
    PRINT 'Tabla anterior renombrada a dbo.DIM_HOMOLOGADOS_BK_20261006';
END
GO

/* 2) Producto externo (catálogo MINSA u otra fuente) – atributos del producto, incl. CodigoSIGA ---- */
IF OBJECT_ID('dbo.DIM_PRODUCTO_EXTERNO', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.DIM_PRODUCTO_EXTERNO (
        FUENTE                  VARCHAR(20)    NOT NULL,
        ID_SKU_EXTERNO          VARCHAR(50)    NOT NULL,
        DESC_PRODUCTO_EXTERNO   NVARCHAR(300)  NULL,
        ID_SKU_EXTERNO_CANONICO VARCHAR(50)    NOT NULL,   -- = ID_SKU_EXTERNO salvo duplicados
        ES_DUPLICADO            BIT            NOT NULL CONSTRAINT DF_DPE_ES_DUPLICADO DEFAULT (0),
        EN_CATALOGO_MINSA       BIT            NOT NULL CONSTRAINT DF_DPE_EN_CATALOGO DEFAULT (1),
        CodigoSIGA              VARCHAR(12)    NULL,
        VALIDACION_SIGA         VARCHAR(10)    NOT NULL CONSTRAINT DF_DPE_VALIDACION_SIGA DEFAULT ('SIN_DATO'),
        SIGA_ESTADO             VARCHAR(30)    NULL,
        CodigoSIGA_SUGERIDO     VARCHAR(12)    NULL,
        DESC_SIGA               NVARCHAR(300)  NULL,
        TIENE_HOMOLOGACION      BIT            NOT NULL CONSTRAINT DF_DPE_TIENE_HOMOLOGACION DEFAULT (0),
        FECHA_ALTA              DATETIME       NOT NULL CONSTRAINT DF_DPE_FECHA_ALTA DEFAULT (GETDATE()),
        USUARIO_ALTA            NVARCHAR(128)  NOT NULL CONSTRAINT DF_DPE_USUARIO_ALTA DEFAULT (SUSER_SNAME()),
        FECHA_MODIFICACION      DATETIME       NULL,
        CONSTRAINT PK_DIM_PRODUCTO_EXTERNO PRIMARY KEY CLUSTERED (FUENTE, ID_SKU_EXTERNO),
        CONSTRAINT CK_DPE_VALIDACION_SIGA CHECK (VALIDACION_SIGA IN ('OK', 'REVISION', 'SIN_DATO')),
        CONSTRAINT CK_DPE_SIGA_OK CHECK (VALIDACION_SIGA <> 'OK' OR CodigoSIGA IS NOT NULL)
    );
    CREATE INDEX IX_DPE_CodigoSIGA ON dbo.DIM_PRODUCTO_EXTERNO (CodigoSIGA) WHERE CodigoSIGA IS NOT NULL;
    CREATE INDEX IX_DPE_CANONICO ON dbo.DIM_PRODUCTO_EXTERNO (FUENTE, ID_SKU_EXTERNO_CANONICO);
END
GO

/* 3) Homologación producto externo -> SKU Unilene ---------------------------------------------- */
IF OBJECT_ID('dbo.DIM_HOMOLOGADOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.DIM_HOMOLOGADOS (
        ID_HOMOLOGACION             INT IDENTITY(1, 1) NOT NULL,
        ID_SKU_EXTERNO              VARCHAR(50)    NOT NULL,
        DESC_PRODUCTO_EXTERNO       NVARCHAR(300)  NULL,
        FUENTE                      VARCHAR(20)    NOT NULL,
        ID_SKU_UNICO_UNILENE        VARCHAR(30)    NULL,
        ID_SKU_UNILENE              VARCHAR(20)    NOT NULL,
        AGRUPADOR                   NVARCHAR(100)  NULL,
        SUBAGRUPADOR                NVARCHAR(150)  NULL,
        AGRUPADOR_NEWCOMERCIAL      NVARCHAR(100)  NULL,
        SUB_AGRUPADOR_NEWCOMERCIAL  NVARCHAR(150)  NULL,
        LINEA_NEWCOMERCIAL          NVARCHAR(100)  NULL,
        DPRO_DESC_SUB_FAMILIA       NVARCHAR(150)  NULL,
        VALIDACION                  VARCHAR(10)    NOT NULL CONSTRAINT DF_DH_VALIDACION DEFAULT ('REVISION'),
        MOTIVO_REVISION             NVARCHAR(200)  NULL,
        NIVEL                       VARCHAR(10)    NOT NULL CONSTRAINT DF_DH_NIVEL DEFAULT ('EXACTO'),
        ORIGEN                      NVARCHAR(100)  NULL,
        FECHA_ALTA                  DATETIME       NOT NULL CONSTRAINT DF_DH_FECHA_ALTA DEFAULT (GETDATE()),
        USUARIO_ALTA                NVARCHAR(128)  NOT NULL CONSTRAINT DF_DH_USUARIO_ALTA DEFAULT (SUSER_SNAME()),
        FECHA_MODIFICACION          DATETIME       NULL,
        USUARIO_MODIFICACION        NVARCHAR(128)  NULL,
        CONSTRAINT PK_DIM_HOMOLOGADOS_V2 PRIMARY KEY CLUSTERED (ID_HOMOLOGACION),
        CONSTRAINT UQ_DIM_HOMOLOGADOS_V2 UNIQUE (FUENTE, ID_SKU_EXTERNO, ID_SKU_UNILENE),
        CONSTRAINT CK_DH_VALIDACION CHECK (VALIDACION IN ('OK', 'REVISION', 'RECHAZADO')),
        CONSTRAINT CK_DH_NIVEL CHECK (NIVEL IN ('EXACTO', 'REVISION')),
        CONSTRAINT FK_DH_PRODUCTO FOREIGN KEY (FUENTE, ID_SKU_EXTERNO)
            REFERENCES dbo.DIM_PRODUCTO_EXTERNO (FUENTE, ID_SKU_EXTERNO)
    );
    CREATE INDEX IX_DH_SKU_UNILENE ON dbo.DIM_HOMOLOGADOS (ID_SKU_UNILENE) INCLUDE (FUENTE, ID_SKU_EXTERNO, VALIDACION);
    CREATE INDEX IX_DH_SKU_UNICO ON dbo.DIM_HOMOLOGADOS (ID_SKU_UNICO_UNILENE);
END
GO

/* 4) Candidatos pendientes de validación ---------------------------------------------------------- */
IF OBJECT_ID('dbo.HOMOLOGACION_REVISION', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.HOMOLOGACION_REVISION (
        ID_REVISION           INT IDENTITY(1, 1) NOT NULL,
        FUENTE                VARCHAR(20)    NOT NULL,
        ID_SKU_EXTERNO        VARCHAR(50)    NOT NULL,
        ID_SKU_UNILENE        VARCHAR(20)    NOT NULL,
        ID_SKU_UNICO_UNILENE  VARCHAR(30)    NULL,
        ITEM_UNILENE          NVARCHAR(300)  NULL,
        TIER_COL_F            VARCHAR(20)    NULL,   -- probable / revisar / exacto / base_dim
        COL                   VARCHAR(10)    NULL,   -- C, I, J
        PRIORIDAD             TINYINT        NULL,   -- 1 = C, 2 = I, 3 = J
        SCORE                 TINYINT        NULL,
        DIFERENCIAS           NVARCHAR(300)  NULL,
        VENDIDO_MINSA         CHAR(2)        NULL,
        ORIGEN                NVARCHAR(100)  NULL,
        DECISION              CHAR(2)        NULL,   -- SI / NO
        FECHA_DECISION        DATETIME       NULL,
        USUARIO_DECISION      NVARCHAR(128)  NULL,
        FECHA_APLICACION      DATETIME       NULL,   -- cuando se pasó a DIM_HOMOLOGADOS
        FECHA_ALTA            DATETIME       NOT NULL CONSTRAINT DF_HR_FECHA_ALTA DEFAULT (GETDATE()),
        CONSTRAINT PK_HOMOLOGACION_REVISION PRIMARY KEY CLUSTERED (ID_REVISION),
        CONSTRAINT UQ_HOMOLOGACION_REVISION UNIQUE (FUENTE, ID_SKU_EXTERNO, ID_SKU_UNILENE),
        CONSTRAINT CK_HR_DECISION CHECK (DECISION IS NULL OR DECISION IN ('SI', 'NO'))
    );
END
GO

